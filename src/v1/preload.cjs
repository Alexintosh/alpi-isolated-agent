const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("isolated", Object.freeze({
  connect: () => ipcRenderer.invoke("isolated:connect"),
  disconnect: () => ipcRenderer.invoke("isolated:disconnect"),
  status: () => ipcRenderer.invoke("isolated:status"),
  selectEnvironment: id => ipcRenderer.invoke("isolated:select", id),
  stopEnvironment: () => ipcRenderer.invoke("isolated:stop"),
  manageEnvironment: operation => ipcRenderer.invoke("isolated:environment-manage", operation),
  quit: () => ipcRenderer.invoke("isolated:quit"),
  switchDesktopImage: id => ipcRenderer.invoke("isolated:desktop-image-switch",id),
  importDesktopImage: () => ipcRenderer.invoke("isolated:desktop-image-import"),
  cancelDesktopImageImport: () => ipcRenderer.invoke("isolated:desktop-image-cancel"),
  showViewer: kind => ipcRenderer.invoke("isolated:viewer-open", kind),
  showPanel: panel => ipcRenderer.invoke("isolated:panel", panel),
  decideNetwork: (id, decision) => ipcRenderer.invoke("isolated:network-decision", id, decision),
  revokeNetwork: id => ipcRenderer.invoke("isolated:network-revoke", id),
  addNetworkRule: rule => ipcRenderer.invoke("isolated:network-add", rule),
  setNetworkMode: (id, mode) => ipcRenderer.invoke("isolated:network-mode", id, mode),
  decideNetworkGroup: (key, decision) => ipcRenderer.invoke("isolated:network-group-decision", key, decision),
  dismissNetworkNotice: key => ipcRenderer.invoke("isolated:network-notice-dismiss", key),
  clearNetworkHistory: () => ipcRenderer.invoke("isolated:network-clear"),
  importModels: () => ipcRenderer.invoke("isolated:model-import"),
  probeModels: () => ipcRenderer.invoke("isolated:model-probe"),
  importGit: repository => ipcRenderer.invoke('isolated:git-import', repository),
  removeGit: id => ipcRenderer.invoke('isolated:git-remove', id),
  importFiles: input => ipcRenderer.invoke("isolated:file-import", input),
  exportFiles: input => ipcRenderer.invoke("isolated:file-export", input),
  executeTransfer: id => ipcRenderer.invoke("isolated:file-execute", id),
  cancelTransfer: () => ipcRenderer.invoke("isolated:file-cancel"),
  recoverTransfer: (id, action) => ipcRenderer.invoke('isolated:file-recover', id, action),
  setResources: value => ipcRenderer.invoke('isolated:resources-set',value),
  exportDiagnostics:()=>ipcRenderer.invoke('isolated:diagnostics-export'),
  installRuntime:()=>ipcRenderer.invoke('isolated:runtime-install'),
  rollbackRuntime:()=>ipcRenderer.invoke('isolated:runtime-rollback'),
  restoreRuntime:()=>ipcRenderer.invoke('isolated:runtime-restore'),
  cancelRuntimeInstall:()=>ipcRenderer.invoke('isolated:runtime-cancel'),
  prepareShare: mode => ipcRenderer.invoke('isolated:share-prepare', { mode }),
  confirmShare: id => ipcRenderer.invoke('isolated:share-confirm', id),
  removeShare: id => ipcRenderer.invoke('isolated:share-remove', id),
  cancelShare: () => ipcRenderer.invoke('isolated:share-cancel'),
  saveSecret: input => ipcRenderer.invoke('isolated:secret-save', input),
  removeSecret: id => ipcRenderer.invoke('isolated:secret-remove', id),
  onStatus: callback => {
    const listener = (_event, value) => callback(value);
    ipcRenderer.on("isolated:status", listener);
    return () => ipcRenderer.removeListener("isolated:status", listener);
  },
}));
